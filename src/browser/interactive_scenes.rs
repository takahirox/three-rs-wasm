/// `Color.setHSL`, returning sRGB components.
fn hsl(h: f64, s: f64, l: f64) -> [f64; 3] {
    let hue = |p: f64, q: f64, t: f64| {
        let t = t.rem_euclid(1.);
        if t < 1. / 6. {
            p + (q - p) * 6. * t
        } else if t < 0.5 {
            q
        } else if t < 2. / 3. {
            p + (q - p) * 6. * (2. / 3. - t)
        } else {
            p
        }
    };
    let q = if l <= 0.5 {
        l * (1. + s)
    } else {
        l + s - l * s
    };
    let p = 2. * l - q;
    let h = h.rem_euclid(1.);
    [hue(p, q, h + 1. / 3.), hue(p, q, h), hue(p, q, h - 1. / 3.)]
}
/// `GridHelper( size, divisions )` with its default colors.
fn grid_helper(size: f64, divisions: u32) -> Result<Line> {
    let (center, step, half) = (divisions / 2, size / divisions as f64, size / 2.);
    let (mut vertices, mut colors) = (vec![], vec![]);
    let mut k = -half;
    for i in 0..=divisions {
        vertices.extend([-half, 0., k, half, 0., k, k, 0., -half, k, 0., half].map(|v| v as f32));
        let c = Color::from_hex(if i == center { 0x444444 } else { 0x888888 }).0;
        for _ in 0..4 {
            colors.extend(c.to_array().map(|v| v as f32));
        }
        k += step;
    }
    let mut g = BufferGeometry::default();
    g.set_attribute("position", positions(vertices)?);
    g.set_attribute("color", positions(colors)?);
    let mut m = LineBasicMaterial::default();
    m.properties.vertex_colors = true;
    Ok(Line {
        geometry: Arc::new(g),
        material: Arc::new(Material::Line(m)),
        segments: true,
    })
}
/// `PlaneHelper( plane, 2, hex )`: an outline strip and a translucent one-sided quad.
fn plane_helper(s: &mut Scene, parent: Object3D, hex: u32) -> Result<Object3D> {
    let mut g = BufferGeometry::default();
    g.set_attribute(
        "position",
        positions(vec![
            1., -1., 0., -1., 1., 0., -1., -1., 0., 1., 1., 0., -1., 1., 0., -1., -1., 0., 1., -1.,
            0., 1., 1., 0.,
        ])?,
    );
    let mut m = LineBasicMaterial::default();
    m.properties.color = Color::from_hex(hex);
    let h = s.insert(NodeKind::Line(Line {
        geometry: Arc::new(g),
        material: Arc::new(Material::Line(m)),
        segments: false,
    }));
    let mut g = BufferGeometry::default();
    g.set_attribute(
        "position",
        positions(vec![
            1., 1., 0., -1., 1., 0., -1., -1., 0., 1., 1., 0., -1., -1., 0., 1., -1., 0.,
        ])?,
    );
    let mut m = MeshBasicMaterial::default();
    m.properties.color = Color::from_hex(hex);
    m.properties.opacity = 0.2;
    m.properties.transparent = true;
    m.properties.depth_write = false;
    let quad = s.insert(NodeKind::Mesh(Mesh::new(
        Arc::new(g),
        Arc::new(Material::Basic(m)),
    )));
    s.add(h, quad)?;
    s.add(parent, h)?;
    Ok(h)
}
/// Label canvas as generated by the original `generateLabelMaterial`.
fn label(text: &str, background: &str) -> Result<crate::material::Texture> {
    let fail = |e: wasm_bindgen::JsValue| Error::Asset(format!("label canvas: {e:?}"));
    let canvas = web_sys::OffscreenCanvas::new(128, 32).map_err(fail)?;
    let context = canvas
        .get_context("2d")
        .map_err(fail)?
        .ok_or(Error::Invalid("label context"))?
        .dyn_into::<web_sys::OffscreenCanvasRenderingContext2d>()
        .map_err(|e| fail(e.into()))?;
    context.set_fill_style_str(background);
    context.fill_rect(0., 0., 128., 32.);
    context.set_fill_style_str("white");
    context.set_font("bold 11pt arial");
    context.fill_text(text, 8., 22.).map_err(fail)?;
    let data = context
        .get_image_data(0., 0., 128., 32.)
        .map_err(fail)?
        .data()
        .to_vec();
    let mut t = crate::material::Texture::from_rgba(128, 32, data, true)?;
    t.mipmap_filter = Some(Filter::Linear);
    Ok(t)
}
/// Unlit textured material whose display (sRGB) output feeds fixed-function blending.
async fn blend_material(r: &Renderer, t: &GpuTexture) -> Result<ShaderMaterial> {
    let tex = tsl::Texture::External(0).sample(vec2(uv().x(), float(1.) - uv().y()));
    let rgb = call(
        "blend_encode",
        "fn blend_encode(c:vec3<f32>)->vec3<f32>{return srgb_output(c);}",
        &[Type::Vec3],
        Type::Vec3,
        &[tex.clone().rgb()],
    )?;
    let mut m = NodeMaterial::new(vec4(rgb, tex.swizzle("w")))
        .build(r, &[(&t.view, &t.sampler)])
        .await?;
    m.properties.transparent = true;
    Ok(m)
}

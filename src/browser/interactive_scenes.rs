    async fn blending(&mut self, s: &mut Scene, r: &Renderer) -> Result<()> {
        let mut t = decode_texture_image(
            &fetch(
                "/web/gallery/assets/environment-materials/textures/lensflare/lensflare0_alpha.png",
            )
            .await?,
        )
        .await?;
        t.srgb = true;
        t.mipmap_filter = Some(Filter::Linear);
        let texture = r.upload_texture(&Arc::new(t))?;
        let base = blend_material(r, &texture).await?;
        let (g1, g2) = (
            Arc::new(PlaneGeometry::build(100., 100., 1, 1)?),
            Arc::new(PlaneGeometry::build(100., 25., 1, 1)?),
        );
        // The destination list is the source list without SrcAlphaSaturate.
        for (i, &dst) in SRC[..10].iter().enumerate() {
            for (j, &src) in SRC.iter().enumerate() {
                let mut m = base.clone();
                m.properties.blending = Some(custom_blend(src, dst, 0));
                let h = s.insert(NodeKind::Mesh(Mesh::new(
                    g1.clone(),
                    Arc::new(Material::Shader(m)),
                )));
                let y = (i as f64 - 5.) * 110. + 50.;
                s.get_mut(h)?.position = Vector3::new((j as f64 - 5.5) * 110., -y, 0.);
                self.blends.push((h, src, dst));
            }
        }
        for (names, color, horizontal) in [
            (&SRC_NAMES[..], "rgba( 0, 150, 0, 1 )", true),
            (&SRC_NAMES[..10], "rgba( 150, 0, 0, 1 )", false),
        ] {
            for (k, name) in names.iter().enumerate() {
                let t = r.upload_texture(&Arc::new(label(name, color)?))?;
                let m = blend_material(r, &t).await?;
                let h = s.insert(NodeKind::Mesh(Mesh::new(
                    g2.clone(),
                    Arc::new(Material::Shader(m)),
                )));
                s.get_mut(h)?.position = if horizontal {
                    Vector3::new((k as f64 - 5.5) * 110., -(-500. - 70.), 0.)
                } else {
                    let y = (k as f64 - 5.) * 110. + 165.;
                    Vector3::new(-5.5 * 110. - 125., -(y - 120.), 0.)
                };
            }
        }
        // The same checker background as webgl_materials_blending, repeat (64, 32).
        let mut rgba = vec![];
        for y in 0..128 {
            for x in 0..128 {
                let v = if x < 64 && y < 64 {
                    if x >= 32 && y >= 32 { 0x99 } else { 0x55 }
                } else if x >= 64 && y >= 64 {
                    if x >= 96 && y >= 96 { 0x77 } else { 0x55 }
                } else {
                    0xdd
                };
                rgba.extend([v, v, v, 255]);
            }
        }
        let mut t = crate::material::Texture::from_rgba(128, 128, rgba, true)?;
        t.wrap_s = Wrapping::Repeat;
        t.wrap_t = Wrapping::Repeat;
        t.mipmap_filter = Some(Filter::Linear);
        let t = r.upload_texture(&Arc::new(t))?;
        let coordinate = vec2(
            uv().x() * float(64.) - uniform(0, Type::Float) * float(0.16),
            (float(1.) - uv().y()) * float(32.) + uniform(0, Type::Float) * float(0.08),
        );
        let color = call(
            "blend_background",
            "fn blend_background(c:vec4<f32>)->vec4<f32>{return vec4(srgb_output(c.rgb),c.a);}",
            &[Type::Vec4],
            Type::Vec4,
            &[tsl::Texture::External(0).sample(coordinate)],
        )?;
        let graph = NodeMaterial::new(color);
        let mut m = ShaderMaterial::new(Arc::new(
            ShaderProgram::with_projection(
                r,
                &graph.wgsl(1)?,
                &[],
                &[(&t.view, &t.sampler)],
                FULLSCREEN,
            )
            .await?,
        ));
        m.properties.depth_write = false;
        m.properties.depth_test = false;
        let h = s.insert(NodeKind::Mesh(Mesh::new(
            Arc::new(PlaneGeometry::build(1., 1., 1, 1)?),
            Arc::new(Material::Shader(m)),
        )));
        s.get_mut(h)?.frustum_culled = false;
        s.get_mut(h)?.render_order = -10000;
        self.background = Some(h);
        Ok(())
    }
    /// `PlaneHelper.updateMatrixWorld`: lookAt( normal ), then translateZ( -constant ).
    fn place_helpers(&self, s: &mut Scene) -> Result<()> {
        let Some(group) = self.helpers else {
            return Ok(());
        };
        let children = s.get(group)?.children().to_vec();
        for (h, plane) in children.into_iter().zip(&self.planes) {
            let n = s.get_mut(h)?;
            n.position = Vector3::ZERO;
            n.scale = Vector3::new(1., 1., 1.);
            s.look_at(h, plane.normal)?;
            let n = s.get_mut(h)?;
            n.translate_on_axis(Vector3::Z, -plane.constant);
        }
        Ok(())
    }
    fn raycast(&self, s: &Scene, c: Object3D) -> Result<Option<crate::raycast::Intersection>> {
        let (camera, world) = s.camera(c)?;
        let mut ray = Raycaster::default();
        ray.set_from_camera(self.pointer, camera, world)?;
        Ok(ray
            .intersect_objects(s, &self.objects, false)?
            .into_iter()
            .next())
    }
    /// Three.js `intersect.face.normal`: the local, unflipped triangle normal.
    fn face_normal(s: &Scene, hit: &crate::raycast::Intersection) -> Result<Vector3> {
        let g = s
            .get(hit.object)?
            .geometry()
            .ok_or(Error::Invalid("hit geometry"))?
            .clone();
        let p = g.positions()?;
        let f = hit.face_index.ok_or(Error::Invalid("hit face"))? * 3;
        let [a, b, c] = [f, f + 1, f + 2].map(|i| g.vertex_index(i).map(|i| p[i]));
        let (a, b, c) = (a?, b?, c?);
        Ok((c - b).cross(a - b).normalize())
    }
    fn snap(s: &Scene, hit: &crate::raycast::Intersection) -> Result<Vector3> {
        let p = hit.point + Self::face_normal(s, hit)?;
        Ok((p / 50.).floor() * 50. + Vector3::splat(25.))
    }
    pub fn update(&mut self, _s: &mut Scene, _c: Object3D, dt: f64, animate: bool) -> Result<()> {
        if animate {
            self.time += dt;
        }
        Ok(())
    }
    pub fn prepare(&mut self, s: &mut Scene, c: Object3D) -> Result<()> {
        let t = self.time;
        self.apply_parameters(s)?;
        if [195, 196].contains(&self.id) {
            self.orbit.apply(s, c)?;
        }
        match self.id {
            194 => {
                let mesh = self.objects[0];
                s.get_mut(mesh)?.quaternion = Euler {
                    angles: Vector3::new(t * 0.15, t * 0.25, 0.),
                    order: EulerOrder::XYZ,
                }
                .quaternion();
                s.update()?;
                let line = self.line.ok_or(Error::Invalid("line"))?;
                if let Some(hit) = self.raycast(s, c)? {
                    let g = s
                        .get(mesh)?
                        .geometry()
                        .ok_or(Error::Invalid("mesh"))?
                        .clone();
                    let p = g.positions()?;
                    let f = hit.face_index.ok_or(Error::Invalid("hit face"))? * 3;
                    // copyAt( a, b, c, a ), then applyMatrix4( mesh.matrix ) on the line.
                    let matrix = s.get(mesh)?.matrix_world;
                    let mut data = vec![];
                    for i in [f, f + 1, f + 2, f] {
                        let v = p[i].as_vec3().as_dvec3();
                        data.extend(matrix.transform_point3(v).to_array().map(|x| x as f32));
                    }
                    let n = s.get_mut(line)?;
                    if let NodeKind::Line(l) = &mut n.kind {
                        Arc::make_mut(&mut l.geometry).set_attribute("position", positions(data)?);
                    }
                    n.visible = true;
                } else {
                    s.get_mut(line)?.visible = false;
                }
            }
            196 => {
                let (camera, world) = s.camera(c)?;
                let (camera, node) = (camera.clone(), s.get(c)?.clone());
                let _ = world;
                if let Some(cmp) = &mut self.comparison {
                    let n = cmp.scene.get_mut(cmp.camera)?;
                    n.kind = NodeKind::Camera(camera);
                    n.position = node.position;
                    n.quaternion = node.quaternion;
                }
            }
            197 => {
                if let Some(h) = self.background
                    && let NodeKind::Mesh(m) = &mut s.get_mut(h)?.kind
                    && let Material::Shader(m) = Arc::make_mut(&mut m.materials[0])
                {
                    m.uniforms[0][0] = t as f32;
                }
            }
            _ => {}
        }
        Ok(())
    }
    /// Scissored rendering of the two comparison scenes into a shared target.
    pub fn render(
        &mut self,
        r: &Renderer,
        s: &mut Scene,
        c: Object3D,
        out: &RenderTarget,
    ) -> Result<bool> {
        let Some(cmp) = &mut self.comparison else {
            return Ok(false);
        };
        if cmp.output.as_ref().is_none_or(|t| {
            t.width != out.width
                || t.height != out.height
                || t.options.samples != out.options.samples
        }) {
            let mut options = out.options.clone();
            options.store_multisampled_color_buffer = true;
            cmp.output = Some(RenderTarget::with_options(
                &r.device, out.width, out.height, options,
            )?);
        }
        let target = cmp.output.as_mut().expect("comparison target");
        let dpr = web_sys::window()
            .map(|w| w.device_pixel_ratio())
            .unwrap_or(1.);
        let split = ((cmp.slider * dpr).round() as u32).min(out.width);
        target.set_load_color(false);
        target.scissor = Some([0, 0, split.max(1), out.height]);
        r.render(s, c, target)?;
        if split < out.width {
            target.set_load_color(true);
            target.scissor = Some([split, 0, out.width - split, out.height]);
            r.render(&mut cmp.scene, cmp.camera, target)?;
        }
        target.scissor = None;
        Ok(true)
    }
    pub fn output(&self) -> Option<&RenderTarget> {
        self.comparison.as_ref().and_then(|c| c.output.as_ref())
    }
    pub fn gpu_pointer(&mut self, s: &mut Scene, c: Object3D, x: f64, y: f64) -> Result<bool> {
        self.pointer = Vector2::new(x, y);
        if self.id != 193 {
            return Ok(false);
        }
        s.update()?;
        if let Some(hit) = self.raycast(s, c)? {
            let p = Self::snap(s, &hit)?;
            s.get_mut(self.rollover.ok_or(Error::Invalid("rollover"))?)?
                .position = p;
            return Ok(true);
        }
        Ok(false)
    }
    pub fn select(&mut self, s: &mut Scene, c: Object3D, x: f64, y: f64) -> Result<()> {
        if self.id != 193 {
            return Ok(());
        }
        self.pointer = Vector2::new(x, y);
        s.update()?;
        let Some(hit) = self.raycast(s, c)? else {
            return Ok(());
        };
        if self.shift {
            if hit.object != self.objects[0] {
                self.objects.retain(|h| *h != hit.object);
                s.dispose(hit.object)?;
            }
        } else {
            let p = Self::snap(s, &hit)?;
            let (g, m) = self.voxel.clone().ok_or(Error::Invalid("voxel"))?;
            let h = s.insert(NodeKind::Mesh(Mesh::new(g, m)));
            s.get_mut(h)?.position = p;
            self.objects.push(h);
        }
        Ok(())
    }
    pub fn key(&mut self, code: u32, down: bool) {
        if code == 16 {
            self.shift = down;
        }
    }
    pub fn slider(&mut self, x: f64) {
        if let Some(c) = &mut self.comparison {
            c.slider = x;
        }
    }
    #[allow(clippy::too_many_arguments)]
    pub fn input(
        &mut self,
        s: &Scene,
        c: Object3D,
        dx: f64,
        dy: f64,
        wheel: f64,
        pan: bool,
        height: f64,
    ) -> Result<()> {
        if ![195, 196].contains(&self.id) {
            return Ok(());
        }
        if pan {
            if self.id == 195 {
                return Ok(());
            }
            let Camera::Perspective(p) = s.camera(c)?.0 else {
                return Ok(());
            };
            self.orbit.pan(s.get(c)?, p.fov, dx, dy, height);
        } else if wheel != 0. {
            self.orbit.dolly(wheel);
        } else {
            self.orbit.rotate(dx, dy, height);
        }
        // The controls' pointer and wheel handlers call update() themselves.
        self.orbit.update();
        Ok(())
    }
    pub fn parameter(&mut self, index: usize, value: f32) -> Result<()> {
        match (self.id, index) {
            (195, 0..=3) if value.is_finite() => self.params[index] = value,
            (197, 0) if (0. ..=4.).contains(&value) => self.equation = value as usize,
            _ => return Err(Error::Invalid("interactive scene parameter")),
        }
        self.dirty = true;
        Ok(())
    }
    fn apply_parameters(&mut self, s: &mut Scene) -> Result<()> {
        if !std::mem::take(&mut self.dirty) {
            return Ok(());
        }
        if self.id == 197 {
            for &(h, src, dst) in &self.blends {
                if let NodeKind::Mesh(m) = &mut s.get_mut(h)?.kind {
                    Arc::make_mut(&mut m.materials[0]).properties_mut().blending =
                        Some(custom_blend(src, dst, self.equation));
                }
            }
            return Ok(());
        }
        for p in &mut self.planes {
            p.constant = self.params[2] as f64;
        }
        for &h in &self.objects {
            if let NodeKind::Mesh(m) = &mut s.get_mut(h)?.kind {
                let p = Arc::make_mut(&mut m.materials[0]).properties_mut();
                p.alpha_to_coverage = self.params[0] != 0.;
                p.clip_intersection = self.params[1] != 0.;
                p.clipping_planes = self.planes.clone();
            }
        }
        if let Some(h) = self.helpers {
            s.get_mut(h)?.visible = self.params[3] != 0.;
        }
        self.place_helpers(s)
    }
    pub fn seek(&mut self, t: f64) {
        self.time = t;
    }

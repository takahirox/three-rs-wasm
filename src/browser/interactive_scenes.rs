/// CustomBlending: the alpha channel reuses the color factors and equation. WebGPU
/// requires One factors for min/max, which GL ignores for those equations.
fn custom_blend(
    src: wgpu::BlendFactor,
    dst: wgpu::BlendFactor,
    equation: usize,
) -> wgpu::BlendState {
    use wgpu::{BlendFactor as F, BlendOperation as O};
    let operation = [O::Add, O::Subtract, O::ReverseSubtract, O::Min, O::Max][equation];
    let (src_factor, dst_factor) = if equation >= 3 {
        (F::One, F::One)
    } else {
        (src, dst)
    };
    let c = wgpu::BlendComponent {
        src_factor,
        dst_factor,
        operation,
    };
    wgpu::BlendState { color: c, alpha: c }
}

"""Generates tsl/src/three/**/mod.rs and tsl/src/three/order.rs: the ported
modules ( a Rust file per JS file, same relative path in snake case ) and
their initialization in the ES module evaluation order of Three.WebGPU.js,
then the addons' ( addons/ ) in the pages' import order."""
import os, re

ROOT = os.path.join(os.path.dirname(__file__), '../..')
TREE = os.path.join(ROOT, 'tsl/src/three')
KEYWORDS = {'core', 'loop', 'type', 'match', 'mod', 'fn', 'impl', 'use', 'ref', 'self', 'super', 'move', 'box', 'where', 'const', 'static', 'struct', 'enum', 'trait', 'crate', 'extern', 'in', 'as', 'break', 'continue', 'else', 'if', 'for', 'while', 'return', 'true', 'false', 'let', 'mut', 'pub', 'unsafe', 'dyn', 'async', 'await', 'abstract', 'final', 'override', 'virtual', 'yield', 'try', 'macro', 'priv', 'typeof', 'unsized', 'do', 'become'}

def snake(name):
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', s)
    s = s.replace('-', '_').replace('.', '_').lower()
    s = re.sub(r'_+', '_', s)
    return s + '_' if s in KEYWORDS else s

SRC = os.path.join(ROOT, '.cache/three-r187/src')

def rust_path(js):
    # An addon ( ../examples/jsm/… ) goes under addons/.
    if js.startswith('../examples/jsm/'):
        return ['addons'] + [snake(p) for p in js[len('../examples/jsm/'):-3].split('/')]
    parts = js[:-3].split('/')
    out = [snake(p) for p in parts]
    if js.endswith('.original.js'):
        return out
    d = os.path.join(SRC, *parts[:-1])
    if os.path.isdir(d) and any(os.path.isdir(os.path.join(d, f)) and snake(f) == out[-1] for f in os.listdir(d)):
        out[-1] += '_mod'
    return out

def main():
    def ported_of(name):
        order = open(os.path.join(ROOT, '.cache/tslsrc', name)).read().split('\n')
        return [(js, rust_path(js)) for js in order if os.path.exists(os.path.join(TREE, *rust_path(js)) + '.rs')]
    ported = ported_of('module_order.txt')
    addons = ported_of('addon_order.txt')
    # mod.rs per directory.
    dirs = {}
    for js, rp in ported + addons:
        for i in range(len(rp)):
            dirs.setdefault(tuple(rp[:i]), set()).add(rp[i])
    for d, children in dirs.items():
        path = os.path.join(TREE, *d, 'mod.rs')
        lines = ['//! Generated by tools/tsl/gen_mods.py.']
        if d == ('addons',):
            lines += ['//! The addons ( examples/jsm ) the ported pages use, transpiled as `src/` is', '//! ( tools/tsl/transpile.mjs ); `order::init_addons` evaluates them.']
        for c in sorted(children):
            lines.append(f'pub mod {c};')
        if d == ():
            lines.append('pub mod order;')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write('\n'.join(lines) + '\n')
    lines = ['//! Generated by tools/tsl/gen_mods.py: module initialization in ES evaluation order.',
             '', '/// Evaluate every ported module once.', 'pub fn init_all() -> crate::rt::R<()> {']
    for js, rp in ported:
        lines.append(f'    crate::reg::run_module("{js}", super::{"::".join(rp)}::init)?;')
    lines.append('    Ok(())')
    lines.append('}')
    lines += ['', '/// Evaluate the ported addons ( after `init_all` ), in the ES evaluation',
              '/// order of the pages\' imports: MaterialXLoader, then MaterialXInterfaceValidation.',
              'pub fn init_addons() -> crate::rt::R<()> {']
    for js, rp in addons:
        lines.append(f'    crate::reg::run_module("{js}", super::{"::".join(rp)}::init)?;')
    lines += ['    Ok(())', '}']
    open(os.path.join(TREE, 'order.rs'), 'w').write('\n'.join(lines) + '\n')
    print(len(ported), 'modules,', len(addons), 'addons')

main()

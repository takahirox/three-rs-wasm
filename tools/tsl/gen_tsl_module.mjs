// Generates web/gallery/tsl-module.js: `three/tsl` for the editor's user code
// ( the gallery's import map points the specifier here ). Its exports are the
// port's Three.TSL.js namespace, which the editor page installs as
// globalThis.__tslNamespace before running any code.
import fs from 'node:fs';
const root = new URL( '../../', import.meta.url ).pathname;
const names = JSON.parse( fs.readFileSync( root + 'tests/tsl/tsl-exports.json', 'utf8' ) );
const lines = [ '// Generated by tools/tsl/gen_tsl_module.mjs: the port\'s three/tsl ( the three-tsl crate ).', 'const ns = globalThis.__tslNamespace;' ];
for ( const n of names ) lines.push( `export const ${ n } = ns.${ n };` );
fs.writeFileSync( root + 'web/gallery/tsl-module.js', lines.join( '\n' ) + '\n' );
console.log( names.length, 'exports' );

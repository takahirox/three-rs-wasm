"""Generates tsl/src/three/constants.rs from r187's src/constants.js: every
export, numbers, strings and the flat object literals, in source order."""
import os, re

ROOT = os.path.join(os.path.dirname(__file__), '../..')
src = open(os.path.join(ROOT, '.cache/three-r187/src/constants.js')).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'//[^\n]*', '', src)
out = ['//! r187 `src/constants.js`, generated by tools/tsl/gen_constants.py.',
       'use crate::reg::export;', 'use crate::rt::*;', '',
       'const M: &str = "constants.js";', '', 'pub fn init() -> R<()> {']

def value(v):
    v = v.strip()
    if re.fullmatch(r"'[^']*'", v):
        return f'Val::from({v.replace(chr(39), chr(34))})'
    if re.fullmatch(r'-?[0-9.e+-]+', v):
        return f'Val::Num({float(v)!r})'
    raise ValueError(v)

for m in re.finditer(r'export const (\w+) = (\{.*?\}|[^;]+);', src, re.S):
    name, v = m.group(1), m.group(2).strip()
    if v.startswith('{'):
        entries = []
        for part in v[1:-1].split(','):
            if not part.strip():
                continue
            k, val = part.split(':', 1)
            entries.append(f'("{k.strip()}", {value(val)})')
        out.append(f'    export(M, "{name}", object(&[{", ".join(entries)}]));')
    else:
        out.append(f'    export(M, "{name}", {value(v)});')
out.append('    Ok(())')
out.append('}')
path = os.path.join(ROOT, 'tsl/src/three/constants.rs')
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, 'w').write('\n'.join(out) + '\n')
print(len(out) - 8, 'constants')
